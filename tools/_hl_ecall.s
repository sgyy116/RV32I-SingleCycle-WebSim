# ============================================================================
# _hl_ecall.s —— 专测「ecall 触发的异常」这一条路径的夹具
#
# _hl_test.s 里最后一条 mret 跳飞后是靠「非法指令」（cause=2）进的 trap，
# 走的是 illegal 那条支路。ecall 是 cause=11，图上 ecall 网络标签和 illegal
# 是两条不同的线，得单独跑一遍才算数。
#
# mtvec 故意不配置（=0），所以 ecall 之后 CPU 直接停机——
# 这样 ecall 那一周期就是最后一个周期，翻出来看最省事。
# ============================================================================

    lui  x2, 0x80001        # x2 = 0x80001000（有效数据地址，必须在 0x80000000 以上）
    addi x1, x0, 4
    sw   x1, 0(x2)          # 往数据区写 4
    lw   x3, 0(x2)          # 读回来，把访存通路先跑通
    addi x4, x0, 1
    beq  x1, x3, ok         # 4 == 4 → 跳成功
    addi x5, x0, 99         # 不该执行到
ok:
    ecall                   # 触发环境调用异常（cause=11），mtvec=0 → 停机
    addi x6, x0, 7          # 不该执行到
